// Screenshots of each funnel step. Usage: node scripts/funnel-shots.mjs [w] [h]
import { chromium } from "playwright";
const [w = "390", h = "844"] = process.argv.slice(2);
const base = process.env.BASE_URL || "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await (await browser.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: 1 })).newPage();
const log = [];
page.on("console", (m) => m.type() === "error" && log.push(m.text()));
page.on("response", async (r) => { if (r.url().includes("/api/checkout")) log.push("checkout " + r.status() + " " + (await r.text()).slice(0, 200)); });
const snap = (n) => page.screenshot({ path: `shots/f-${w}-${n}.png` });
await page.goto(base + "/");
await page.getByRole("button", { name: "Try a sample statement" }).click();
await page.waitForTimeout(2500);
await page.locator("#scan").scrollIntoViewIfNeeded();
await snap("1-scanning");
await page.getByRole("button", { name: "See my full leak report" }).last().waitFor({ timeout: 60000 });
await page.locator("#scan").evaluate((e) => e.scrollIntoView({ block: "start" }));
await page.waitForTimeout(800);
await snap("2-locked");
await page.getByRole("button", { name: "See my full leak report" }).last().click();
await page.waitForTimeout(800);
await snap("3-signup");
const d = page.getByRole("dialog", { name: "Save your leak report" });
await d.getByPlaceholder("Email").fill(`shot+${Date.now()}@budgeto-test.dev`);
await d.getByPlaceholder(/Create a password/).fill("Leaks-are-bad-2026");
await d.getByRole("button", { name: "Create my account" }).click();
await page.getByText("Choose your plan.").waitFor();
await page.waitForTimeout(1200);
await snap("4-paywall");
await page.getByRole("dialog", { name: "Choose your plan" }).getByRole("button", { name: /^Continue with / }).first().click();
await page.waitForTimeout(6000);
await snap("5-checkout");
await page.getByRole("dialog", { name: "Checkout" }).getByRole("button", { name: "Close" }).click();
await page.waitForTimeout(500);
await page.getByRole("dialog", { name: "Choose your plan" }).getByRole("button", { name: "Close" }).click();
await page.waitForTimeout(800);
await snap("6-closed");
console.log(log.join("\n") || "no errors");
await browser.close();
